# Theme
# ──────────────────────────────────────────────────────────────────────────────

def set_theme(mount_root: str, color_scheme: str, username: str,
              progress_cb: ProgressCB = None):
    if progress_cb:
        progress_cb("Applying theme preferences…")

    # Update gschema override
    override_path = os.path.join(mount_root, "usr/share/glib-2.0/schemas/99_nebulaos.gschema.override")
    if os.path.exists(override_path):
        with open(override_path, "r") as f:
            content = f.read()
        content = re.sub(
            r"color-scheme='[^']*'",
            f"color-scheme='{color_scheme}'",
            content
        )
        with open(override_path, "w") as f:
            f.write(content)

    try:
        _chroot(mount_root, ["glib-compile-schemas", "/usr/share/glib-2.0/schemas"])
    except Exception:
        pass

    # User dconf overrides
    user_home = os.path.join(mount_root, "home", username)
    dconf_dir = os.path.join(user_home, ".config", "dconf")
    os.makedirs(dconf_dir, exist_ok=True)


