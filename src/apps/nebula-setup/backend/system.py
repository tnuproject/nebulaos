def create_user(mount_root: str, username: str, full_name: str, password: str,
                avatar_url: Optional[str] = None, progress_cb: ProgressCB = None):
    if progress_cb:
        progress_cb(f"Creating user '{username}'…")

    # Remove live user 'nebula' if chosen username is different
    if username != "nebula":
        try:
            _chroot(mount_root, ["userdel", "-r", "-f", "nebula"])
        except Exception:
            pass
        live_home = os.path.join(mount_root, "home", "nebula")
        shutil.rmtree(live_home, ignore_errors=True)

    # Check if user already exists
    user_exists = False
    try:
        _chroot(mount_root, ["id", username])
        user_exists = True
    except Exception:
        user_exists = False

    if not user_exists:
        _chroot(mount_root, [
            "useradd",
            "-m", "-s", "/bin/bash",
            "-c", full_name,
            username
        ])

    # Add to administrative, hardware, and desktop groups
    for grp in ["sudo", "audio", "video", "plugdev", "netdev", "bluetooth", "adm", "dialout", "cdrom", "dip", "users"]:
        try:
            _chroot(mount_root, ["usermod", "-aG", grp, username])
        except Exception:
            pass

    # Set password
    passwd_proc = subprocess.Popen(
        ["chroot", mount_root, "chpasswd"],
        stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.PIPE
    )
    passwd_proc.communicate(input=f"{username}:{password}\n".encode())

    # AccountsService profile — configure BOTH Session=gnome (Wayland) and XSession=gnome (X11)
    accounts_dir = os.path.join(mount_root, "var", "lib", "AccountsService", "users")
    os.makedirs(accounts_dir, exist_ok=True)
    account_file = os.path.join(accounts_dir, username)
    with open(account_file, "w") as f:
        f.write(textwrap.dedent(f"""
            [User]
            Language=
            Session=gnome
            XSession=gnome
            SystemAccount=false
            Icon=/home/{username}/.face
        """).strip() + "\n")

    # Copy DefaultUser avatar
    default_face_src = "/usr/share/pixmaps/faces/default.png"
    if not os.path.exists(os.path.join(mount_root, default_face_src.lstrip("/"))):
        default_face_src = None

    user_home = os.path.join(mount_root, "home", username)
    face_dest = os.path.join(user_home, ".face")
    if default_face_src and os.path.exists(os.path.join(mount_root, default_face_src.lstrip("/"))):
        shutil.copy(os.path.join(mount_root, default_face_src.lstrip("/")), face_dest)

    # If avatar URL provided, try to download it
    if avatar_url:
        try:
            import urllib.request
            urllib.request.urlretrieve(avatar_url, face_dest)
        except Exception:
            pass

    # Set AccountsService avatar
    icon_dest = os.path.join(mount_root, "var", "lib", "AccountsService", "icons", username)
    if os.path.exists(face_dest):
        shutil.copy(face_dest, icon_dest)

    # Update AccountsService icon reference
    with open(account_file, "w") as f:
        f.write(textwrap.dedent(f"""
            [User]
            Language=
            Session=gnome
            XSession=gnome
            SystemAccount=false
            Icon=/var/lib/AccountsService/icons/{username}
        """).strip() + "\n")

    # Critical security permissions: AccountsService refuses to read directory if not 0700
    try:
        _chroot(mount_root, ["chown", "-R", "root:root", "/var/lib/AccountsService"])
        _chroot(mount_root, ["chmod", "700", "/var/lib/AccountsService/users"])
        _chroot(mount_root, ["chmod", "600", f"/var/lib/AccountsService/users/{username}"])
    except Exception:
        pass

    # Ensure ~/.dmrc session fallback
    try:
        user_dmrc = os.path.join(user_home, ".dmrc")
        with open(user_dmrc, "w") as f:
            f.write("[Desktop]\nSession=gnome\n")
    except Exception:
        pass

    # Fix ownership and permissions of entire user home
    try:
        uid_gid = subprocess.check_output(
            ["chroot", mount_root, "id", "-u", username], text=True
        ).strip()
        subprocess.run(["chown", "-R", f"{uid_gid}:{uid_gid}", user_home],
                       capture_output=True)
        subprocess.run(["chmod", "700", user_home], capture_output=True)
        subprocess.run(["chmod", "-R", "u+rwX", user_home], capture_output=True)
        subprocess.run(["chmod", "644", os.path.join(user_home, ".dmrc")], capture_output=True)
    except Exception:
        pass


