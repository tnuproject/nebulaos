def install_bootloader(mount_root: str, device: str, use_efi: bool,
                       install_mode: str = "erase",
                       progress_cb: ProgressCB = None):
    if progress_cb:
        progress_cb("Installing bootloader…")

    env = {"DEBIAN_FRONTEND": "noninteractive"}

    # Ensure os-prober is enabled in /etc/default/grub for detecting other OSes
    grub_default = os.path.join(mount_root, "etc/default/grub")
    if os.path.exists(grub_default):
        with open(grub_default, "r") as f:
            content = f.read()
        if "GRUB_DISABLE_OS_PROBER=" in content:
            content = re.sub(r"GRUB_DISABLE_OS_PROBER=.*", "GRUB_DISABLE_OS_PROBER=false", content)
        else:
            content += "\nGRUB_DISABLE_OS_PROBER=false\n"

        if install_mode == "dualboot":
            content = re.sub(r"GRUB_TIMEOUT=.*", "GRUB_TIMEOUT=5", content)
            content = re.sub(r"GRUB_TIMEOUT_STYLE=.*", "GRUB_TIMEOUT_STYLE=menu", content)

        with open(grub_default, "w") as f:
            f.write(content)

    # In dualboot mode, make sure silent snippet doesn't suppress the GRUB menu
    silent_cfg = os.path.join(mount_root, "etc/default/grub.d/00_nebula_silent.cfg")
    if install_mode == "dualboot" and os.path.exists(silent_cfg):
        try:
            with open(silent_cfg, "w") as f:
                f.write("GRUB_TIMEOUT=5\nGRUB_TIMEOUT_STYLE=menu\nGRUB_DISABLE_OS_PROBER=false\n")
        except Exception:
            pass

    if use_efi:
        try:
            _chroot(mount_root,
                    ["apt-get", "install", "-y", "--no-install-recommends",
                     "grub-efi-amd64", "efibootmgr"],
                    env=env)
        except Exception:
            pass

        # Standard UEFI GRUB install to /boot/efi
        _chroot(mount_root, [
            "grub-install",
            "--target=x86_64-efi",
            "--efi-directory=/boot/efi",
            "--bootloader-id=NebulaOS",
            "--recheck"
        ])

        # Also install fallback removable EFI binary (/boot/efi/EFI/BOOT/BOOTX64.EFI)
        try:
            _chroot(mount_root, [
                "grub-install",
                "--target=x86_64-efi",
                "--efi-directory=/boot/efi",
                "--bootloader-id=NebulaOS",
                "--recheck",
                "--removable"
            ])
        except Exception:
            pass
    else:
        try:
            _chroot(mount_root,
                    ["apt-get", "install", "-y", "--no-install-recommends", "grub-pc"],
                    env=env)
        except Exception:
            pass

        _chroot(mount_root, [
            "grub-install",
            "--target=i386-pc",
            "--recheck",
            device
        ])

    if progress_cb:
        progress_cb("Detecting operating systems & generating bootloader configuration…")
    _chroot(mount_root, ["update-grub"])


