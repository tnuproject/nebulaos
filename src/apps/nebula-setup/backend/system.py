def setup_locale(mount_root: str, language: str, timezone: str,
                 keyboard_layout: str, keyboard_model: str,
                 progress_cb: ProgressCB = None):
    if progress_cb:
        progress_cb("Setting locale and timezone…")

    # locale.gen
    locale_gen = os.path.join(mount_root, "etc", "locale.gen")
    with open(locale_gen, "w") as f:
        f.write(f"{language}.UTF-8 UTF-8\n")
        if not language.startswith("en_US"):
            f.write("en_US.UTF-8 UTF-8\n")

    try:
        _chroot(mount_root, ["locale-gen"])
    except Exception:
        pass

    # /etc/locale.conf
    locale_conf = os.path.join(mount_root, "etc", "locale.conf")
    with open(locale_conf, "w") as f:
        f.write(f"LANG={language}.UTF-8\nLC_ALL={language}.UTF-8\n")

    # Default locale
    default_locale = os.path.join(mount_root, "etc", "default", "locale")
    with open(default_locale, "w") as f:
        f.write(f'LANG="{language}.UTF-8"\n')

    # Timezone via symlink
    tz_src = os.path.join(mount_root, "usr", "share", "zoneinfo", timezone)
    tz_dest = os.path.join(mount_root, "etc", "localtime")
    if os.path.exists(tz_src):
        if os.path.exists(tz_dest) or os.path.islink(tz_dest):
            os.remove(tz_dest)
        os.symlink(f"/usr/share/zoneinfo/{timezone}", tz_dest)

    # /etc/timezone
    tz_file = os.path.join(mount_root, "etc", "timezone")
    with open(tz_file, "w") as f:
        f.write(timezone + "\n")

    # Keyboard
    keyboard_conf = os.path.join(mount_root, "etc", "default", "keyboard")
    with open(keyboard_conf, "w") as f:
        f.write(textwrap.dedent(f"""
            XKBMODEL="{keyboard_model}"
            XKBLAYOUT="{keyboard_layout}"
            XKBVARIANT=""
            XKBOPTIONS=""
            BACKSPACE="guess"
        """).strip() + "\n")


def apply_live_keyboard_layout(keyboard_layout: str, keyboard_model: str = "pc105"):
    """
    Applies the keyboard layout immediately to the live running system/desktop session.
    Updates GNOME input-sources, setxkbmap, localectl, and /etc/default/keyboard.
    """
    try:
        from gi.repository import Gio, GLib
        settings = Gio.Settings.new("org.gnome.desktop.input-sources")
        builder = GLib.VariantBuilder.new(GLib.VariantType.new("a(ss)"))
        builder.add_value(GLib.Variant("(ss)", ("xkb", keyboard_layout)))
        settings.set_value("sources", builder.end())
        settings.apply()
    except Exception:
        pass

    # Update GSettings for the live session user via subprocess/dbus if running under sudo/pkexec
    for u in [os.environ.get("SUDO_USER"), "nebula"]:
        if not u:
            continue
        try:
            cmd = f'gsettings set org.gnome.desktop.input-sources sources "[(\\\'xkb\\\', \\\'{keyboard_layout}\\\')]"'
            subprocess.run(["su", "-", u, "-c", cmd], capture_output=True, timeout=2)
        except Exception:
            pass

    # setxkbmap for X11 / Xwayland
    try:
        subprocess.run(["setxkbmap", "-layout", keyboard_layout, "-model", keyboard_model], capture_output=True, timeout=2)
    except Exception:
        pass

    # localectl for systemd
    try:
        subprocess.run(["localectl", "set-x11-keymap", keyboard_layout, keyboard_model], capture_output=True, timeout=2)
        subprocess.run(["localectl", "set-keymap", keyboard_layout], capture_output=True, timeout=2)
    except Exception:
        pass

    # Live /etc/default/keyboard
    try:
        with open("/etc/default/keyboard", "w") as f:
            f.write(textwrap.dedent(f"""
                XKBMODEL="{keyboard_model}"
                XKBLAYOUT="{keyboard_layout}"
                XKBVARIANT=""
                XKBOPTIONS=""
                BACKSPACE="guess"
            """).strip() + "\n")
        subprocess.run(["udevadm", "trigger", "--subsystem-match=input", "--action=change"], capture_output=True, timeout=2)
    except Exception:
        pass


def apply_live_timezone(timezone: str):
    """
    Applies timezone immediately to the live system clock.
    """
    try:
        subprocess.run(["timedatectl", "set-timezone", timezone], capture_output=True, timeout=2)
        tz_src = f"/usr/share/zoneinfo/{timezone}"
        if os.path.exists(tz_src):
            if os.path.exists("/etc/localtime") or os.path.islink("/etc/localtime"):
                try: os.remove("/etc/localtime")
                except Exception: pass
            try: os.symlink(tz_src, "/etc/localtime")
            except Exception: pass
    except Exception:
        pass


def apply_live_theme(color_scheme: str):
    """
    Applies theme (prefer-dark / prefer-light) immediately to the live session and installer UI.
    """
    try:
        from gi.repository import Gio, Adw
        style_mgr = Adw.StyleManager.get_default()
        if color_scheme == "prefer-dark":
            style_mgr.set_color_scheme(Adw.ColorScheme.PREFER_DARK)
        else:
            style_mgr.set_color_scheme(Adw.ColorScheme.PREFER_LIGHT)

        settings = Gio.Settings.new("org.gnome.desktop.interface")
        settings.set_string("color-scheme", color_scheme)
        settings.apply()
    except Exception:
        pass



