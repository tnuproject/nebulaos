# Unpack squashfs
# ──────────────────────────────────────────────────────────────────────────────

def unpack_squashfs(mount_root: str, squashfs_path: str, progress_cb: ProgressCB = None):
    """Unpack squashfs filesystem into mount_root."""
    if progress_cb:
        progress_cb("Unpacking filesystem…")

    # Clean any temporary contents in mount_root if needed (skip lost+found and boot)
    try:
        for item in os.listdir(mount_root):
            if item in ["lost+found", "boot"]:
                continue
            item_path = os.path.join(mount_root, item)
            if os.path.isdir(item_path) and not os.path.islink(item_path):
                shutil.rmtree(item_path, ignore_errors=True)
            else:
                try:
                    os.remove(item_path)
                except Exception:
                    pass
    except Exception:
        pass

    # Fallback squashfs paths
    import glob
    sources = [
        squashfs_path,
        "/cdrom/live/filesystem.squashfs",
        "/run/live/medium/live/filesystem.squashfs",
        "/lib/live/mount/medium/live/filesystem.squashfs",
        "/run/live/rootfs/filesystem.squashfs",
    ]
    sources += glob.glob("/run/live/**/filesystem.squashfs", recursive=True)
    sources += glob.glob("/lib/live/**/filesystem.squashfs", recursive=True)
    sources += glob.glob("/cdrom/**/filesystem.squashfs", recursive=True)

    actual_source = None
    for s in sources:
        if s and os.path.isfile(s):
            actual_source = s
            break

    if not actual_source:
        raise FileNotFoundError(f"squashfs not found at any expected path: {sources}")

    subprocess.run(
        ["unsquashfs", "-f", "-d", mount_root, actual_source],
        check=True
    )


# ──────────────────────────────────────────────────────────────────────────────
# Virtual filesystems (for chroot operations)
# ──────────────────────────────────────────────────────────────────────────────

def bind_vfs(mount_root: str):
    for fs, src, ftype in [
        ("/dev", "/dev", None),
        ("/dev/pts", "/dev/pts", None),
        ("/proc", None, "proc"),
        ("/sys", None, "sysfs"),
    ]:
        target = mount_root + fs
        os.makedirs(target, exist_ok=True)
        if src:
            subprocess.run(["mount", "--bind", src, target],
                           check=True, capture_output=True)
        else:
            subprocess.run(["mount", "-t", ftype, ftype, target],
                           check=True, capture_output=True)

    # Bind efivarfs if booted in UEFI mode
    efivars_host = "/sys/firmware/efi/efivars"
    if os.path.isdir(efivars_host):
        target = os.path.join(mount_root, "sys/firmware/efi/efivars")
        os.makedirs(target, exist_ok=True)
        subprocess.run(["mount", "--bind", efivars_host, target], capture_output=True)


def unbind_vfs(mount_root: str):
    for fs in [
        "/sys/firmware/efi/efivars",
        "/boot/efi",
        "/dev/pts",
        "/dev",
        "/proc",
        "/sys",
    ]:
        target = mount_root + fs
        subprocess.run(["umount", "-lf", target], capture_output=True)


