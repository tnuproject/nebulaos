# ──────────────────────────────────────────────────────────────────────────────
# Post-install cleanup
# ──────────────────────────────────────────────────────────────────────────────

def post_cleanup(mount_root: str, username: str, install_mode: str = "erase",
                 progress_cb: ProgressCB = None):
    if progress_cb:
        progress_cb("Running post-install cleanup…")

    cleanup_script = os.path.join(mount_root, "usr/lib/nebulaos/post-install-cleanup.sh")
    if os.path.exists(cleanup_script):
        try:
            _chroot(mount_root, ["/usr/lib/nebulaos/post-install-cleanup.sh", username, install_mode])
        except Exception:
            pass

    # Completely remove installer, setup files, and autostarts from target system
    for path in [
        os.path.join(mount_root, "usr/bin/nebula-setup"),
        os.path.join(mount_root, "usr/bin/install-nebula"),
        os.path.join(mount_root, "usr/bin/nebula-installer"),
        os.path.join(mount_root, "usr/bin/nebula-session-init"),
        os.path.join(mount_root, "usr/share/nebula-setup"),
        os.path.join(mount_root, "usr/share/applications/installer.desktop"),
        os.path.join(mount_root, "usr/share/applications/install-nebula.desktop"),
        os.path.join(mount_root, "usr/share/applications/nebula-installer-autostart.desktop"),
        os.path.join(mount_root, "usr/share/applications/calamares.desktop"),
        os.path.join(mount_root, "usr/share/applications/install-debian.desktop"),
        os.path.join(mount_root, "etc/xdg/autostart/nebula-installer-autostart.desktop"),
        os.path.join(mount_root, "etc/xdg/autostart/calamares.desktop"),
        os.path.join(mount_root, "etc/xdg/autostart/calamares-desktop-icon.desktop"),
        os.path.join(mount_root, "home", username, "Desktop/installer.desktop"),
        os.path.join(mount_root, "home", username, "Desktop/install-nebula.desktop"),
        os.path.join(mount_root, "etc/skel/Desktop/installer.desktop"),
        os.path.join(mount_root, "etc/skel/Desktop/install-nebula.desktop"),
    ]:
        try:
            if os.path.isdir(path) and not os.path.islink(path):
                shutil.rmtree(path, ignore_errors=True)
            elif os.path.exists(path):
                os.remove(path)
        except Exception:
            pass

    # Enable NetworkManager
    try:
        _chroot(mount_root, ["systemctl", "enable", "NetworkManager"])
    except Exception:
        pass

    # Configure GDM3 daemon.conf on installed system: Wayland enabled, clean login prompt, strictly default to GNOME
    gdm_dir = os.path.join(mount_root, "etc", "gdm3")
    os.makedirs(gdm_dir, exist_ok=True)
    gdm_conf = os.path.join(gdm_dir, "daemon.conf")
    try:
        with open(gdm_conf, "w") as f:
            f.write(textwrap.dedent("""
                [daemon]
                AutomaticLoginEnable = false
                WaylandEnable = true
                DefaultSession = gnome.desktop

                [security]

                [xdmcp]

                [chooser]

                [debug]
            """).strip() + "\n")
        os.chmod(gdm_conf, 0o644)
    except Exception:
        pass

    # Ensure GDM PreSession script guarantees Session=gnome for all users
    try:
        presession_dir = os.path.join(mount_root, "etc", "gdm3", "PreSession")
        os.makedirs(presession_dir, exist_ok=True)
        presession_file = os.path.join(presession_dir, "Default")
        hook = (
            '\nif [ -n "$USER" ] && [ -f "/var/lib/AccountsService/users/$USER" ]; then\n'
            '    sed -i "s|^Session=.*|Session=gnome|" "/var/lib/AccountsService/users/$USER" 2>/dev/null || true\n'
            'fi\n'
        )
        if os.path.exists(presession_file):
            with open(presession_file, "r") as f:
                content = f.read()
            if "Session=gnome" not in content:
                with open(presession_file, "a") as f:
                    f.write(hook)
        else:
            with open(presession_file, "w") as f:
                f.write("#!/bin/sh\n" + hook + "exit 0\n")
            os.chmod(presession_file, 0o755)
    except Exception:
        pass

    # Ensure /home/{username} is completely owned by user with correct permissions
    user_home = os.path.join(mount_root, "home", username)

    if os.path.isdir(user_home):
        try:
            _chroot(mount_root, ["chown", "-R", f"{username}:{username}", f"/home/{username}"])
            _chroot(mount_root, ["chmod", "700", f"/home/{username}"])
            _chroot(mount_root, ["chmod", "-R", "u+rwX", f"/home/{username}"])
        except Exception:
            pass

    # Update desktop DB so installer disappears from the app list
    try:
        _chroot(mount_root, ["update-desktop-database", "/usr/share/applications"])
    except Exception:
        pass

    if progress_cb:
        progress_cb("Finalizing…")


