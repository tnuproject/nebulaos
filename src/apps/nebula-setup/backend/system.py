def setup_resolv(mount_root: str):
    src = "/etc/resolv.conf"
    dest = os.path.join(mount_root, "etc", "resolv.conf")
    try:
        if os.path.islink(dest):
            os.remove(dest)
        shutil.copy2(src, dest)
    except Exception:
        pass
