def setup_fstab(mount_root: str, root_part: str, efi_part: Optional[str],
                progress_cb: ProgressCB = None):
    if progress_cb:
        progress_cb("Configuring filesystems table…")

    root_uuid = get_uuid(root_part)
    lines = ["# /etc/fstab — generated by Nebula Setup\n"]

    if root_uuid:
        lines.append(f"UUID={root_uuid}\t/\text4\terrors=remount-ro\t0\t1\n")
    else:
        lines.append(f"{root_part}\t/\text4\terrors=remount-ro\t0\t1\n")

    if efi_part:
        efi_uuid = get_uuid(efi_part)
        if efi_uuid:
            lines.append(f"UUID={efi_uuid}\t/boot/efi\tvfat\tumask=0077\t0\t1\n")
        else:
            lines.append(f"{efi_part}\t/boot/efi\tvfat\tumask=0077\t0\t1\n")

    lines.append("tmpfs\t/tmp\ttmpfs\tnosuid,nodev\t0\t0\n")

    fstab_path = os.path.join(mount_root, "etc", "fstab")
    with open(fstab_path, "w") as f:
        f.writelines(lines)


