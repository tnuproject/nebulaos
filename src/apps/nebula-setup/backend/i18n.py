_current_lang = "en"
_listeners: List[Callable[[], None]] = []


def set_language(locale_code: str):
    """Set the active translation language and notify all registered UI listeners."""
    global _current_lang
    prefix = locale_code.split("_")[0].lower()
    _current_lang = prefix if prefix in TRANSLATIONS else "en"
    for listener in _listeners:
        try:
            listener()
        except Exception:
            pass


def get_language() -> str:
    return _current_lang


def t(key: str) -> str:
    """Translate string key for current language with English fallback."""
    table = TRANSLATIONS.get(_current_lang, TRANSLATIONS["en"])
    return table.get(key, TRANSLATIONS["en"].get(key, key))


def register_listener(fn: Callable[[], None]):
    """Register a UI refresh callback when language changes."""
    if fn not in _listeners:
        _listeners.append(fn)
